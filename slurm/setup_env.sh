#!/usr/bin/env bash
# Create venv for the attr-patch mini-project on Ada u22 compute nodes.
# /share1 is login-only. Use /ssd_scratch (node-local) for venv + HF cache.
set -euo pipefail

SHARE_LOGIN="${SHARE_LOGIN:-/share1/hrishiraj.mitra}"
HOME_MP="${HOME_MP:-$HOME/mp}"
SCRATCH_BASE="${SCRATCH_BASE:-/ssd_scratch/$USER}"
VENV="${VENV:-$SCRATCH_BASE/venvs/mp-attrpatch}"
HF_HOME="${HF_HOME:-$SCRATCH_BASE/hf}"
RESULTS="${RESULTS:-$HOME_MP/results}"
PIPCACHE="${PIPCACHE:-$HOME/pipcache}"
MP_PIPCACHE="${MP_PIPCACHE:-$HOME/pipcache/mp-attrpatch}"

if [[ -z "${PYTHON:-}" ]]; then
  if [[ -x /software/apps/u22/python/3.12.15/bin/python3 ]]; then
    PYTHON=/software/apps/u22/python/3.12.15/bin/python3
  elif [[ -x /software/apps/u22/python/3.12.4/bin/python3 ]]; then
    PYTHON=/software/apps/u22/python/3.12.4/bin/python3
  else
    PYTHON="$(command -v python3)"
  fi
fi

mkdir -p "$SCRATCH_BASE/venvs" "$HF_HOME" "$RESULTS" "$MP_PIPCACHE" \
         "$HOME/mp-attrpatch-logs" "$HOME_MP"

if ! "$PYTHON" -c 'import sys; print(sys.version)' >/dev/null 2>&1; then
  echo "ERROR: $PYTHON cannot start. Run on a u22 compute node." >&2
  exit 1
fi

echo "Host=$(hostname)"
echo "PYTHON=$PYTHON ($("$PYTHON" -c 'import sys; print(sys.version.split()[0])'))"
echo "VENV=$VENV"
nvidia-smi --query-gpu=name --format=csv,noheader || true

unset PYTHONHOME || true

if [[ ! -x "$VENV/bin/python" ]]; then
  echo "Creating venv at $VENV"
  "$PYTHON" -m venv "$VENV"
else
  echo "Venv exists: $VENV — refreshing packages"
fi

# shellcheck disable=SC1091
source "$VENV/bin/activate"
unset PYTHONHOME || true
export PATH="$VENV/bin:$PATH"

python -m pip install --upgrade pip wheel setuptools

# Prefer offline/local wheels (home pipcache) — cluster CDN to download.pytorch.org is slow
echo "Installing torch from local pipcache if present..."
if ls "$PIPCACHE"/torch-*.whl >/dev/null 2>&1; then
  pip install --no-index --find-links="$PIPCACHE" torch
else
  pip install --cache-dir "$MP_PIPCACHE" --index-url https://download.pytorch.org/whl/cu121 \
    'torch>=2.1.0,<2.5.0'
fi

REQ="$HOME_MP/requirements.txt"
if [[ -f "$REQ" ]]; then
  # Install remaining deps; allow torch already satisfied
  pip install --cache-dir "$MP_PIPCACHE" --find-links="$PIPCACHE" -r "$REQ" || \
    pip install --cache-dir "$MP_PIPCACHE" -r "$REQ"
else
  pip install --cache-dir "$MP_PIPCACHE" --find-links="$PIPCACHE" \
    'transformer-lens>=2.0.0' numpy scipy pandas matplotlib tqdm einops \
    jaxtyping fancy-einsum transformers accelerate huggingface-hub safetensors datasets
fi

# Skip sae-lens by default: it pins transformer-lens<4 and is unused by Project A.
# pip install --cache-dir "$MP_PIPCACHE" 'sae-lens>=3.0.0' || true

echo "$(hostname)" > "$HOME_MP/.compute_node"
echo "$VENV" > "$HOME_MP/.venv_path"

PYLIB="$(dirname "$(dirname "$PYTHON")")/lib"
cat > "$HOME_MP/env.sh" <<EOF
# Auto-generated by setup_env.sh on $(hostname) at $(date -Iseconds)
unset PYTHONHOME
export LD_LIBRARY_PATH="$PYLIB:\${LD_LIBRARY_PATH:-}"
export HF_HOME="$HF_HOME"
export TRANSFORMERS_CACHE="\$HF_HOME/transformers"
export HF_DATASETS_CACHE="\$HF_HOME/datasets"
export TORCH_HOME="\$HF_HOME/torch"
export VENV="$VENV"
export PATH="$VENV/bin:\$PATH"
export VIRTUAL_ENV="$VENV"
export MP_COMPUTE_NODE="$(hostname)"
export MP_SHARE_LOGIN="$SHARE_LOGIN"
EOF

if [[ -d "$SHARE_LOGIN" ]]; then
  mkdir -p "$SHARE_LOGIN/mp-attrpatch"
  cp "$HOME_MP/env.sh" "$SHARE_LOGIN/mp-attrpatch/env.sh" || true
fi

echo "Done. Pin jobs: sbatch --nodelist=$(hostname) ..."
"$VENV/bin/python" - <<'PY'
import torch
import transformer_lens
print("torch", torch.__version__, "cuda", torch.cuda.is_available())
print("tl", transformer_lens.__version__)
if torch.cuda.is_available():
    print("gpu", torch.cuda.get_device_name(0))
    x = torch.zeros(1, device="cuda")
    print("cuda_tensor_ok", x.device)
PY
